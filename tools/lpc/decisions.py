"""lpc decisions: validate decisions/D-*.yaml against the rubric and render decisions/DECISIONS.md."""
from __future__ import annotations

import sys

import yaml

from .common import DECISIONS

W = {"r1": 0.25, "r2": 0.20, "r3": 0.15, "r4": 0.15, "r5": 0.15, "r6": 0.10}
THRESHOLD = 0.8


def score(o: dict) -> float:
    return round(sum(W[k] * o[k] for k in W), 2)


def run() -> None:
    recs, problems = [], []
    for f in sorted(DECISIONS.glob("D-*.yaml")):
        d = yaml.safe_load(f.read_text())
        opts = d.get("options") or []
        for o in opts:
            if all(k in o for k in W):
                calc = score(o)
                if abs(calc - o.get("score", calc)) > 0.011:
                    problems.append(f"{f.name}: option '{o['name']}' score {o.get('score')} != computed {calc}")
                o["score"] = calc
        scored = sorted([o for o in opts if "score" in o], key=lambda o: -o["score"])
        if d.get("decided_by") == "claude":
            if len(scored) < 2:
                problems.append(f"{f.name}: Claude decisions need at least two scored options")
            else:
                gap = round(scored[0]["score"] - scored[1]["score"], 2)
                if gap < THRESHOLD - 1e-9:
                    problems.append(f"{f.name}: gap {gap} < {THRESHOLD}; this should have gone to the owner")
                d["gap"] = gap
            if not d.get("justification"):
                problems.append(f"{f.name}: Claude decisions need a justification")
        recs.append(d)
    L = ["# Decision log", "", "Generated by `bin/lpc decisions` from `decisions/D-*.yaml`. The rubric is in [RUBRIC.md](../RUBRIC.md).",
         "", "| ID | Date | Decision | Decided by | Chosen | Gap |", "|---|---|---|---|---|---:|"]
    for d in recs:
        L.append(f"| {d['id']} | {d['date']} | {d['title']} | {d['decided_by']} | {d['chosen']} | {d.get('gap', '—')} |")
    for d in recs:
        L += ["", f"## {d['id']} {d['title']}", "", f"*{d['date']} · decided by **{d['decided_by']}***", ""]
        if d.get("context"):
            L += [d["context"].strip(), ""]
        if d.get("options"):
            L += ["| Option | R1 | R2 | R3 | R4 | R5 | R6 | Score |", "|---|---:|---:|---:|---:|---:|---:|---:|"]
            for o in d["options"]:
                cells = " | ".join(str(o.get(k, "–")) for k in W)
                L.append(f"| {'**' + o['name'] + '**' if o['name'] == d['chosen'] else o['name']} | {cells} | {o.get('score', '–')} |")
            L.append("")
        L.append(f"**Chosen:** {d['chosen']}")
        if d.get("owner_answer"):
            L += ["", f"**Owner's answer:** {d['owner_answer']}"]
        if d.get("justification"):
            L += ["", f"**Justification:** {d['justification'].strip()}"]
    (DECISIONS / "DECISIONS.md").write_text("\n".join(L) + "\n")
    for p in problems:
        print("PROBLEM", p)
    print(f"decisions: {len(recs)} records, {len(problems)} problem(s)")
    if problems:
        sys.exit(1)
